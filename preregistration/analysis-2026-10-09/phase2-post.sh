#!/bin/bash
# Phase-2 post-chain pipeline on the dev box (protocol v5.1 sections 八 and 十). No key, no network. Three modes:
#
#   MODE=pre      after the chain is DONE and every batch is judged. BLIND: nothing it prints or writes names a cell.
#                 Time until the coding files were written (module F), the n-gram leak check, the judgments table and
#                 the agreement between judges, and the material of the human leak look.
#   MODE=unblind  after the two human forms are filled:
#                   results/human-check/answers.csv              (the 200 judgements; from answer-template.csv)
#                   results/human-check/leak/leak-answers.csv    (the leak look; from leak-answers-template.csv)
#                 Records their sha256 with the time (sealed.txt), scores them, builds the master table WITH the
#                 judgements and runs the analysis. Refuses to run when a form is missing or incomplete, and when a
#                 sealed form has changed since it was sealed.
#   MODE=blind    a plumbing test at any time: the master table WITHOUT judgements (a judge directory that holds only
#                 the script leak flags) and the analysis on it. Shows money, time and behaviour by cell, no quality.
#
# Usage (dev box, experiment directory):  MODE=pre bash judge-env/scripts/phase2-post.sh
# Do not edit this file while it runs.
P=/weka-hg/prod/deepseek/permanent/zhangziya/private/dsec-exp
cd "$P" || exit 1
source haienv py312-202505 >/dev/null 2>&1
command -v python >/dev/null || { echo "haienv python missing"; exit 1; }
set -u
export PYTHONDONTWRITEBYTECODE=1
MODE=${MODE:?pre, unblind or blind}
J=${J:-judge-env/scripts}
LOG=results/phase2-post.log
log() { echo "[$(date -u +%Y-%m-%dT%H:%M:%SZ)] $*" | tee -a "$LOG"; }
have() { [ -s "results/master/raw/$1.csv" ]; }
REPORT=""; for b in p2-main p2-merge p2-d p2-o; do have $b && REPORT="$REPORT $b"; done
REPORT_CSV=$(echo $REPORT | tr ' ' ',')
ALL="$REPORT"; have p2-f && ALL="$ALL p2-f"
ALL_CSV=$(echo $ALL | tr ' ' ',')
HC=results/human-check
[ -n "$ALL" ] || { log "no phase-2 run table in results/master/raw yet (a batch writes it when it finishes): nothing to do"; exit 1; }
log "mode $MODE; report batches:$REPORT; all:$ALL; scripts $(sha256sum $J/phase2_report.py $J/master_table.py $J/phase2_models.py | cut -c1-12 | tr '\n' ' ')"

retries() {  # seconds each run waited for automatic retries of failed model requests (names no cell)
  for b in $ALL; do
    [ -s results/analysis-$b-retry.json ] || python $J/retry_waits.py results/runs/$b --out results/analysis-$b-retry.json --jobs 16 > results/analysis-$b-retry.txt 2>&1 \
      && log "retry waits $b: $(tail -n 1 results/analysis-$b-retry.txt | cut -c1-200)" || true
    [ -s results/analysis-$b-toolerrors.json ] || PYTHONPATH=$P/$J python $J/tool_errors.py results/runs/$b --out results/analysis-$b-toolerrors.json --jobs 16 > results/analysis-$b-toolerrors.txt 2>&1 \
      && log "tool errors $b: $(head -n 1 results/analysis-$b-toolerrors.txt | cut -c1-200)" || true
  done
}

analysis() {  # $1 judge dir, $2 master out, $3 analysis out
  EXP_ROOT=$P python $J/master_table.py --batches "$ALL_CSV" --out "$2" --raw-dir results/master/raw --judge-dir "$1" > "$2.log" 2>&1 \
    || { log "master table FAILED (see $2.log)"; tail -n 5 "$2.log"; return 1; }
  grep -E '^phase 2|WARNING' "$2.log" | tee -a "$LOG"
  retries; RETRY=$(ls results/analysis-p2-*-retry.json 2>/dev/null | tr '\n' ' ')
  PYTHONPATH=$P/pylib:${PYTHONPATH:-} python $J/phase2_report.py --runs "$2/runs.csv" --out "$3" --merge-index tasks/phase2-merge-index.json --retry $RETRY > "$3.log" 2>&1 \
    || { log "analysis FAILED (see $3.log)"; tail -n 5 "$3.log"; return 1; }
  log "analysis written to $3 ($(grep -c . "$3/contrasts.csv") contrast rows; problems: $(grep -c '^  ' <(sed -n '/PROBLEMS/,$p' "$3/run.log") 2>/dev/null || echo 0))"
}

balance() {  # interface speed by cell (names cells, shows no outcome): request timing from the logs, then the balance table
  for b in $ALL; do
    [ -s results/analysis-$b-reqtiming.json ] || python -u $J/request_timing.py results/runs/$b --json results/analysis-$b-reqtiming.json > results/analysis-$b-reqtiming.txt 2>&1 \
      || { log "request timing $b FAILED"; continue; }
    ref=W-D1-K8
    python $J/phase2_balance.py --timing results/analysis-$b-reqtiming.json --raw results/master/raw/$b.csv --out results/analysis-$b-balance.md --ref $ref \
      --tools results/analysis-$b-toolerrors.json > results/analysis-$b-balance.txt 2>&1 \
      && log "balance $b: $(tail -n 2 results/analysis-$b-balance.txt | head -n 1)" || log "balance $b FAILED (see results/analysis-$b-balance.txt)"
  done
}

case "$MODE" in
pre)
  [ -f results/phase2-chain-DONE.txt ] || { log "the chain is not DONE"; exit 1; }
  pgrep -f '^[^ ]*python[0-9.]* -u [^ ]*(drb2_score|drb2_score_gpt)[.]py' >/dev/null && { log "judging is still running"; exit 1; }
  for b in $REPORT; do
    n_runs=$(($(wc -l < results/master/raw/$b.csv) - 1)); n_judged=$(ls results/drb2-score-gpt/$b/*.r1.json 2>/dev/null | wc -l)
    log "$b: $n_runs runs, $n_judged judge files"
  done
  retries
  if have p2-f; then
    python -u $J/write_timing.py results/runs/p2-f --task toolkit-xl --file-regex '(?:^|/)workspace/(toolkit/.+\.py)$' --units 61 \
      --out results/analysis-p2-f-timing-xl.json > results/analysis-p2-f-timing-xl.txt 2>&1 && log "timing of the large coding task written" || log "timing xl FAILED"
    python -u $J/write_timing.py results/runs/p2-f --task pw-exercises-free --out results/analysis-p2-f-timing-free.json > results/analysis-p2-f-timing-free.txt 2>&1 \
      && log "timing of the 24 exercises written" || log "timing free FAILED"
  fi
  for b in $REPORT; do
    extra=""; [ "$b" = p2-merge ] && extra="--merge-index tasks/phase2-merge-index.json"
    python $J/drb2_ngram_leak.py --reports results/runs/$b --sources judge-env/data/drb2/sources --index tasks/phase2-drb2-index.json $extra \
      --out results/analysis-$b-ngram.csv > results/analysis-$b-ngram.txt 2>&1 && log "n-gram check $b: $(grep -c ',1,' results/analysis-$b-ngram.csv) rows with a 1 (see the file for flags)" || log "n-gram check $b FAILED"
  done
  python $J/phase2_judgments.py --gpt results/drb2-score-gpt --opus results/drb2-score --batches "$REPORT_CSV" --out results/analysis-phase2-judge > results/analysis-phase2-judge.txt 2>&1 \
    && log "judgments table and agreement written (results/analysis-phase2-judge/agreement.md)" || log "judgments FAILED"
  PYTHONPATH=$P/$J python $J/leak_top20.py make --scores results/drb2-score-gpt --batches "$REPORT_CSV" --runs results/runs --index tasks/phase2-drb2-index.json \
    --merge-index tasks/phase2-merge-index.json --out $HC/leak > $HC/leak.out 2>&1 && log "leak look: $(tail -n 3 $HC/leak.out | head -n 1)" || log "leak look FAILED (see $HC/leak.out)"
  log "forms for her: $HC/form.md + $HC/answer-template.csv (save as answers.csv); $HC/leak/leak-form.md + leak-answers-template.csv (save as leak-answers.csv)"
  ;;
unblind)
  A1=$HC/answers.csv; A2=$HC/leak/leak-answers.csv
  [ -s "$A1" ] && [ -s "$A2" ] || { log "a filled form is missing ($A1, $A2): not unblinding"; exit 1; }
  python - "$A1" "$A2" <<'PY' || { echo "a form has empty verdicts: not unblinding"; exit 1; }
import csv, sys
bad = 0
for path in sys.argv[1:]:
    rows = list(csv.DictReader(open(path, encoding="utf-8-sig")))
    empty = [r.get("entry") for r in rows if not (r.get("verdict") or "").strip()]
    print(path, len(rows), "entries,", len(empty), "without a verdict", empty[:10])
    bad += len(empty) or (0 if rows else 1)
raise SystemExit(1 if bad else 0)
PY
  NOW=$(sha256sum "$A1" "$A2")
  if [ -s $HC/sealed.txt ]; then
    [ "$(grep -v '^#' $HC/sealed.txt)" = "$NOW" ] || { log "a form changed after it was sealed (see $HC/sealed.txt): not continuing"; exit 1; }
  else
    { echo "# sealed $(date -u +%Y-%m-%dT%H:%M:%SZ), before the master table was built with judgements"; echo "$NOW"; } > $HC/sealed.txt
    log "forms sealed: $(echo "$NOW" | cut -c1-16 | tr '\n' ' ')"
  fi
  python $J/human_check_sample.py score --answers "$A1" --sample $HC/sample.json > $HC/score.txt 2>&1 && log "human check scored ($HC/score.txt)" || log "human check score FAILED"
  python $J/leak_top20.py score --answers "$A2" --key $HC/leak/leak-key.json --out results/human-leak-flags.json > $HC/leak-score.txt 2>&1 \
    && log "leak look: $(tail -n +2 $HC/leak-score.txt | head -n 1)" || { log "leak look score FAILED"; exit 1; }
  analysis results results/master-p2 results/analysis-phase2 || exit 1
  balance
  log "unblinded: results/analysis-phase2/{confirmatory.md,table1.md,recommend.md,summary.md,contrasts.csv,levels.csv,demand.csv}"
  ;;
blind)
  B=results/blind-judge
  rm -rf $B && mkdir -p $B
  for b in $ALL; do [ -f results/analysis-$b-sources.json ] && ln -s "$P/results/analysis-$b-sources.json" $B/; done
  for f in results/analysis-p2-f-timing-xl.json results/analysis-p2-f-timing-free.json; do [ -f $f ] && ln -s "$P/$f" $B/; done
  analysis $B results/master-p2-blind results/analysis-phase2-blind || exit 1
  balance
  ;;
*) echo "unknown MODE $MODE"; exit 1 ;;
esac
